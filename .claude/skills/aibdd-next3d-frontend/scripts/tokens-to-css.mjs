#!/usr/bin/env node
// Convert W3C DTCG-style color tokens (palette + semantic.light/dark) into CSS custom properties.
// Usage: node tokens-to-css.mjs <tokens.json> <out.css> [--no-tailwind]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const [input, output, ...flags] = process.argv.slice(2);
if (!input || !output) {
  console.error("Usage: node tokens-to-css.mjs <tokens.json> <out.css> [--no-tailwind]");
  process.exit(2);
}
const withTailwind = !flags.includes("--no-tailwind");
const tokens = JSON.parse(readFileSync(input, "utf8"));

const kebab = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/[\s_.]+/g, "-").toLowerCase();

function lookup(path) {
  return path.split(".").reduce((o, k) => (o == null ? undefined : o[k]), tokens);
}

function resolve(value, seen = new Set()) {
  if (value && typeof value === "object" && "$value" in value) value = value.$value;
  if (typeof value !== "string") return value;
  const m = value.match(/^\{([^}]+)\}$/);
  if (!m) return value;
  if (seen.has(m[1])) throw new Error(`Circular reference: ${m[1]}`);
  seen.add(m[1]);
  const target = lookup(m[1]);
  if (target === undefined) throw new Error(`Unresolved reference: ${value}`);
  return resolve(target, seen);
}

function flatten(node, prefix, out) {
  if (node == null) return out;
  if (typeof node === "string" || (typeof node === "object" && "$value" in node)) {
    out.push([prefix, resolve(node)]);
    return out;
  }
  if (Array.isArray(node)) {
    node.forEach((v, i) => flatten(v, `${prefix}-${i + 1}`, out));
    return out;
  }
  if (typeof node === "object") {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith("$")) continue;
      flatten(v, prefix ? `${prefix}-${kebab(k)}` : kebab(k), out);
    }
  }
  return out;
}

const light = tokens.semantic?.light;
const dark = tokens.semantic?.dark;
if (!light) {
  console.error("tokens.semantic.light not found");
  process.exit(1);
}
const lightVars = flatten(light, "", []);
const darkVars = dark ? flatten(dark, "", []) : [];

const decl = (vars, indent) => vars.map(([k, v]) => `${indent}--color-${k}: ${v};`).join("\n");

let css = `/* Generated by tokens-to-css.mjs from ${input.replace(/\\/g, "/")}. Do not edit by hand. */\n`;
css += `/* ${tokens.name ?? "tokens"} ${tokens.version ?? ""} — light is default. */\n\n`;
css += `:root {\n  color-scheme: light;\n${decl(lightVars, "  ")}\n}\n`;
if (darkVars.length) {
  css += `\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n${decl(darkVars, "    ")}\n  }\n}\n`;
  css += `\n:root[data-theme="dark"] {\n  color-scheme: dark;\n${decl(darkVars, "  ")}\n}\n`;
}
if (withTailwind) {
  css += `\n/* Tailwind v4: expose semantic tokens as utilities, e.g. bg-surface-default, text-text-primary */\n@theme inline {\n`;
  css += lightVars.map(([k]) => `  --color-${k}: var(--color-${k});`).join("\n");
  css += `\n}\n`;
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, css, "utf8");

const missingInDark = lightVars.map(([k]) => k).filter((k) => darkVars.length && !darkVars.some(([d]) => d === k));
console.log(`Wrote ${output}: ${lightVars.length} light vars, ${darkVars.length} dark vars.`);
if (missingInDark.length) console.warn(`Warning: ${missingInDark.length} light tokens have no dark counterpart: ${missingInDark.join(", ")}`);
